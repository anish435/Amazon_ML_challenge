"""
Business Entity Resolution — Candidate-Pair Feature Engineering Module
Amazon ML Challenge 2026

This module extracts pairwise comparison features for (Source 1, Candidate) pairs
generated by Blocking V2. The feature representations capture fine-grained
orthographic, lexical, numeric, and cross-field agreement without feeding raw strings
into tabular tree models.

Feature Groups:
1. Name Features (exact matches, edit distance, Jaro-Winkler, token Jaccard/containment, n-grams, lengths)
2. Address Features (exact matches, edit distance, token Jaccard, numeric/PIN agreements, missingness)
3. Country Features (exact match, missingness indicators, open-set safe)
4. Cross-Field Features (interaction terms, signal agreement counts)
"""

import math
from typing import Dict, List, Tuple, Optional, Any, Set, Union
import numpy as np
import polars as pl
from rapidfuzz import fuzz, distance

# Feature Column Definitions
