ALL_FEATURE_COLS: List[str] = (
    NAME_FEATURE_COLS
    + ADDRESS_FEATURE_COLS
    + COUNTRY_FEATURE_COLS
    + CROSS_FEATURE_COLS
    + TARGETED_FEATURE_COLS
)


def _get_char_ngrams(text: str, n: int) -> Set[str]:
    """Extracts character n-grams from a string."""
    if len(text) < n:
        return {text} if text else set()
    return {text[i : i + n] for i in range(len(text) - n + 1)}


def _extract_pin_codes(tokens: List[str]) -> Set[str]:
    """Identifies postal/PIN code candidates (pure 5-6 digit tokens)."""
    return {t for t in tokens if t.isdigit() and len(t) in (5, 6)}


def extract_pair_features(
    s1_norm_name: str,
    s1_core_name: str,
    s1_norm_addr: str,
    s1_country: str,
    cand_norm_name: str,
    cand_core_name: str,
    cand_norm_addr: str,
    cand_country: str,
    s1_raw_name: str = "",
    cand_raw_name: str = "",
) -> List[float]:
    """
    Computes the full vector of comparison features for a single candidate pair.
    Returns a list of floats corresponding to ALL_FEATURE_COLS.
    """
    s1_n = s1_norm_name or ""
    cand_n = cand_norm_name or ""
    s1_c = s1_core_name or ""
    cand_c = cand_core_name or ""

    # ================= 1. NAME FEATURES =================
    name_exact = 1.0 if s1_n and s1_n == cand_n else 0.0
    name_core_exact = 1.0 if s1_c and s1_c == cand_c else 0.0

    len_s1_n = len(s1_n)
    len_cand_n = len(cand_n)

    if len_s1_n > 0 and len_cand_n > 0:
        name_lev = fuzz.ratio(s1_n, cand_n) / 100.0
        name_jw = distance.JaroWinkler.similarity(s1_n, cand_n)
        name_len_diff = float(abs(len_s1_n - len_cand_n))
        name_len_ratio = float(min(len_s1_n, len_cand_n) / max(len_s1_n, len_cand_n))
        name_starts_same = 1.0 if s1_n[0] == cand_n[0] else 0.0
    else:
        name_lev = 0.0
        name_jw = 0.0
        name_len_diff = float(abs(len_s1_n - len_cand_n))
        name_len_ratio = 0.0
        name_starts_same = 0.0

    # Token-level name features (using core names)
    tokens_s1 = set(s1_c.split()) if s1_c else (set(s1_n.split()) if s1_n else set())
    tokens_cand = set(cand_c.split()) if cand_c else (set(cand_n.split()) if cand_n else set())

    len_t1 = len(tokens_s1)
    len_t2 = len(tokens_cand)

    inter_tok = tokens_s1 & tokens_cand
    union_tok = tokens_s1 | tokens_cand
    len_inter = len(inter_tok)

    name_tok_jaccard = float(len_inter / len(union_tok)) if union_tok else 0.0
    name_tok_overlap = float(len_inter)
    name_contain_s1 = float(len_inter / len_t1) if len_t1 > 0 else 0.0
    name_contain_cand = float(len_inter / len_t2) if len_t2 > 0 else 0.0
    name_contain_min = float(len_inter / min(len_t1, len_t2)) if (len_t1 > 0 and len_t2 > 0) else 0.0

    # Character n-grams
    g3_1 = _get_char_ngrams(s1_c or s1_n, 3)
    g3_2 = _get_char_ngrams(cand_c or cand_n, 3)
    name_3gram_jaccard = float(len(g3_1 & g3_2) / max(len(g3_1 | g3_2), 1))

    g2_1 = _get_char_ngrams(s1_c or s1_n, 2)
    g2_2 = _get_char_ngrams(cand_c or cand_n, 2)
    name_2gram_jaccard = float(len(g2_1 & g2_2) / max(len(g2_1 | g2_2), 1))

    name_num_diff = float(abs(len_t1 - len_t2))

    # ================= 2. ADDRESS FEATURES =================
    s1_a = s1_norm_addr or ""
    cand_a = cand_norm_addr or ""

    addr_missing_s1 = 1.0 if not s1_a else 0.0
    addr_missing_cand = 1.0 if not cand_a else 0.0
    addr_both_present = 1.0 if (s1_a and cand_a) else 0.0

    len_s1_a = len(s1_a)
    len_cand_a = len(cand_a)

    nums1: Set[str] = set()
    nums2: Set[str] = set()

    if addr_both_present:
        addr_exact = 1.0 if s1_a == cand_a else 0.0
        addr_lev = fuzz.ratio(s1_a, cand_a) / 100.0
        addr_jw = distance.JaroWinkler.similarity(s1_a, cand_a)
        addr_len_diff = float(abs(len_s1_a - len_cand_a))
        addr_len_ratio = float(min(len_s1_a, len_cand_a) / max(len_s1_a, len_cand_a))

        a_tok1 = set(s1_a.split())
        a_tok2 = set(cand_a.split())
        a_inter = a_tok1 & a_tok2
        a_union = a_tok1 | a_tok2
        addr_tok_jaccard = float(len(a_inter) / len(a_union)) if a_union else 0.0
        addr_tok_overlap = float(len(a_inter))
        addr_tok_contain = float(len(a_inter) / min(len(a_tok1), len(a_tok2))) if (a_tok1 and a_tok2) else 0.0
        addr_num_tokens_diff = float(abs(len(a_tok1) - len(a_tok2)))

        # Address numeric token agreement
        nums1 = {w for w in a_tok1 if any(c.isdigit() for c in w)}
        nums2 = {w for w in a_tok2 if any(c.isdigit() for c in w)}
        num_inter = nums1 & nums2
        num_union = nums1 | nums2
        addr_num_overlap = float(len(num_inter))
        addr_num_jaccard = float(len(num_inter) / len(num_union)) if num_union else 0.0

        if nums1 and nums2:
            addr_num_agreement = 1.0 if len(num_inter) > 0 else -1.0
        else:
            addr_num_agreement = 0.0

        # Postal / PIN code agreement
        pins1 = _extract_pin_codes(list(a_tok1))
        pins2 = _extract_pin_codes(list(a_tok2))
        if pins1 and pins2:
            addr_pin_agreement = 1.0 if len(pins1 & pins2) > 0 else -1.0
        else:
            addr_pin_agreement = 0.0
    else:
        addr_exact = 0.0
        addr_lev = 0.0
        addr_jw = 0.0
        addr_tok_jaccard = 0.0
        addr_tok_overlap = 0.0
        addr_tok_contain = 0.0
        addr_num_overlap = 0.0
        addr_num_jaccard = 0.0
        addr_num_agreement = 0.0
        addr_pin_agreement = 0.0
        addr_len_diff = -1.0
        addr_len_ratio = 0.0
        addr_num_tokens_diff = -1.0

    # ================= 3. COUNTRY FEATURES =================
    c1 = s1_country or "UNKNOWN"
    c2 = cand_country or "UNKNOWN"
    country_exact = 1.0 if (c1 != "UNKNOWN" and c1 == c2) else 0.0
    country_missing_s1 = 1.0 if c1 == "UNKNOWN" else 0.0
    country_missing_cand = 1.0 if c2 == "UNKNOWN" else 0.0

    # ================= 4. CROSS-FIELD FEATURES =================
    name_x_addr = name_lev * addr_lev
    name_exact_addr_exact = 1.0 if (name_exact == 1.0 and addr_exact == 1.0) else 0.0
    name_exact_country_exact = 1.0 if (name_exact == 1.0 and country_exact == 1.0) else 0.0
    num_match_name_sim = addr_num_overlap * name_lev

    # Count of strong agreeing signals
    signals = 0.0
    if name_lev >= 0.85:
        signals += 1.0
    if name_core_exact == 1.0:
        signals += 1.0
    if addr_lev >= 0.80:
        signals += 1.0
    if addr_num_overlap >= 1.0:
        signals += 1.0
    if country_exact == 1.0:
        signals += 1.0
    agreeing_signals_count = signals

    # ================= 5. TARGETED FEATURES (V3) =================
    # Group 1: Address Number Conflict & Exact Match
    addr_num_conflict = 1.0 if (nums1 and nums2 and not (nums1 & nums2)) else 0.0
    addr_num_exact = 1.0 if (nums1 and nums2 and nums1 == nums2) else 0.0

    # Group 2: Missing Address & Name Interactions
    missing_addr_high_name_sim = 1.0 if ((addr_missing_s1 or addr_missing_cand) and name_lev >= 0.85) else 0.0
    missing_addr_exact_core = 1.0 if ((addr_missing_s1 or addr_missing_cand) and name_core_exact == 1.0) else 0.0

    # Group 3: Script Mismatch & Strong-Address/Weak-Name
    name1_repr = s1_raw_name or s1_n
    name2_repr = cand_raw_name or cand_n
    is_s1_asc = all(ord(ch) < 128 for ch in name1_repr) if name1_repr else True
    is_c_asc = all(ord(ch) < 128 for ch in name2_repr) if name2_repr else True
    script_mismatch = 1.0 if (is_s1_asc != is_c_asc) else 0.0
    strong_addr_weak_name = 1.0 if (addr_lev >= 0.75 and name_lev < 0.50) else 0.0

    # Group 4: Strong-Name + Conflicting-Address Interaction
    strong_name_conflicting_addr = 1.0 if (name_lev >= 0.85 and addr_num_conflict == 1.0) else 0.0

    return [
        # Name
        name_exact,
        name_core_exact,
        name_lev,
        name_jw,
        name_tok_jaccard,
        name_tok_overlap,
        name_contain_s1,
        name_contain_cand,
        name_contain_min,
        name_3gram_jaccard,
        name_2gram_jaccard,
        name_len_diff,
        name_len_ratio,
        float(len_t1),
        float(len_t2),
        name_num_diff,
        name_starts_same,
        # Address
        addr_missing_s1,
        addr_missing_cand,
        addr_both_present,
        addr_exact,
        addr_lev,
        addr_jw,
        addr_tok_jaccard,
        addr_tok_overlap,
        addr_tok_contain,
        addr_num_overlap,
        addr_num_jaccard,
        addr_num_agreement,
        addr_pin_agreement,
        addr_len_diff,
        addr_len_ratio,
        addr_num_tokens_diff,
        # Country
        country_exact,
        country_missing_s1,
        country_missing_cand,
        # Cross-Field
        name_x_addr,
        name_exact_addr_exact,
        name_exact_country_exact,
        num_match_name_sim,
        agreeing_signals_count,
        # Targeted (V3)
        addr_num_conflict,
        addr_num_exact,
        missing_addr_high_name_sim,
        missing_addr_exact_core,
        script_mismatch,
        strong_addr_weak_name,
        strong_name_conflicting_addr,
    ]


def build_candidate_feature_matrix(
    candidate_pairs: List[Tuple[str, str]],
    s1_dict: Dict[str, Dict[str, Any]],
    cand_dict: Dict[str, Dict[str, Any]],
    feature_cols: Optional[List[str]] = None,
) -> np.ndarray:
    """
    Constructs a 2D NumPy array of comparison features for a list of (S1_ID, Cand_ID) pairs.
    Memory-efficient, pre-allocated float32 array.
    """
    if feature_cols is None:
        feature_cols = ALL_FEATURE_COLS

    # Determine indices of requested columns
    col_indices = [ALL_FEATURE_COLS.index(col) for col in feature_cols]
    num_pairs = len(candidate_pairs)
    num_cols = len(col_indices)

    matrix = np.empty((num_pairs, num_cols), dtype=np.float32)

    for i, (s1_id, cand_id) in enumerate(candidate_pairs):
        s1 = s1_dict.get(s1_id, {})
        cand = cand_dict.get(cand_id, {})

        raw_feats = extract_pair_features(
            s1_norm_name=s1.get("business_name_norm", ""),
            s1_core_name=s1.get("business_name_core", ""),
            s1_norm_addr=s1.get("business_address_norm", ""),
            s1_country=s1.get("country_norm", ""),
            cand_norm_name=cand.get("business_name_norm", ""),
            cand_core_name=cand.get("business_name_core", ""),
            cand_norm_addr=cand.get("business_address_norm", ""),
            cand_country=cand.get("country_norm", ""),
            s1_raw_name=s1.get("business_name", ""),
            cand_raw_name=cand.get("business_name", ""),
        )

        matrix[i] = [raw_feats[idx] for idx in col_indices]

    return matrix
